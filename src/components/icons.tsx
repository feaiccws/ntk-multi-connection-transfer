export type { LucideIcon };

export function getConnectionTypeIcon(type: string): LucideIcon {
  const map: Record<string, LucideIcon> = {
    ftp: Server,
    sftp: Lock,
    ftps: Shield,
    s3: Cloud,
    google_drive: Folder,
    dropbox: Droplets,
    onedrive: Globe,
    azure_blob: Database,
    local: HardDrive,
    webdav: Globe,
  };
  return map[type] || Server;
}
